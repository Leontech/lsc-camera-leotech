#!/usr/bin/env python3
# LEO build13: embeds web/index.html (+ leotech.cz logo symbol) and favicon into web_html.h
import os, sys
d = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(d, "index.html"), encoding="utf8").read()
logo = open(os.path.join(d, "logo_hidden.svg"), encoding="utf8").read()
html = html.replace("<!--LOGO-->", logo)
fav = open(os.path.join(d, "fav.svg"), "rb").read()
def arr(name, data):
    out = [f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 24):
        out.append(" " + ",".join(str(b) for b in data[i:i+24]) + ",")
    out.append("};")
    out.append(f"static const unsigned int {name}_len = {len(data)};")
    return "\n".join(out)
with open(sys.argv[1], "w") as f:
    f.write("/* generated by web/gen_web_html.py - do not edit */\n#pragma once\n")
    f.write(arr("web_index_html", html.encode("utf8")) + "\n")
    f.write(arr("web_favicon_svg", fav) + "\n")
print("web_html.h:", len(html.encode()), "B html,", len(fav), "B favicon")
